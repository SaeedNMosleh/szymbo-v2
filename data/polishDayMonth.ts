/**
 * Converts a calendar year to the Polish genitive phrase used in dates,
 * e.g. 2026 -> "dwa tysiące dwudziestego szóstego roku".
 * Supports 2001–2099.
 */
export function yearToPolishPhrase(year: number): string {
  if (year < 2001 || year > 2099) {
    throw new Error(`Unsupported year for Polish phrase conversion: ${year}`);
  }

  const lastTwoDigits = year % 100;
  const ordinal = polishYearOrdinalGenitive[lastTwoDigits - 1];
  return `dwa tysiące ${ordinal} roku`;
}
